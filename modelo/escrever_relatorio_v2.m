function escrever_relatorio_v2(dados,T,resumo,checagens,pasta)
% Relatorio sempre calculado a partir dos resultados desta execucao.
arquivo=fullfile(pasta,'RELATORIO_V2.md'); f=fopen(arquivo,'w','n','UTF-8');
assert(f~=-1); fim=onCleanup(@()fclose(f));
m=dados(1).metricas; p=dados(1).parametros;
fprintf(f,'# Resultados locais da v2\n\n');
fprintf(f,'Pista sintetica baseada na ISO 8608:2016, classe C, 72 km/h (20 m/s). ');
fprintf(f,'Cinco trechos de 30 s (600 m), sementes 1 a 5. Planta e controle da v1 preservados; c_sky = %.0f N s/m.\n\n',p.c_sky);
fprintf(f,'## Metodo e criterios\n\n');
fprintf(f,['Gd(n)=256e-6*(n/0.1)^(-2) m^3, com n em ciclos/m. ' ...
 '400 bandas logaritmicas de 0.011 a 2.83 ciclos/m; frequencias temporais de 0.22 a 56.6 Hz. ' ...
 'Amplitude de cada senoide obtida pela integral exata da PSD na banda. ' ...
 'Fases uniformes geradas por RandStream mt19937ar com semente fixa. ' ...
 'A mesma fonte de pista alimenta passiva e semiativa.\n\n']);
fprintf(f,['Subtrai-se apenas a altura inicial, impondo w(0)=0 e fixando a origem vertical. ' ...
 'Nao se normaliza o desvio padrao nem se aplica rampa ao perfil. ' ...
 'A PSD nao nula em frequencia e a rugosidade permanecem iguais. ' ...
 'O veiculo parte do repouso; os primeiros 5 s sao excluidos do RMS principal. ' ...
 'Tambem sao registrados os intervalos 0-30 s e 10-30 s.\n\n']);
fprintf(f,['RMS(a_s)=sqrt(integral(a_s^2 dt)/duracao), integrado por trapz entre 5 e 30 s. ' ...
 'Melhora=100*(1-RMS_semi/RMS_passiva). RMS sem ponderacao ISO 2631, ' ...
 'usado como indicador comparativo de vibracao, nao como percentual de conforto percebido. ' ...
 'Carga dinamica: RMS(N-(m_s+m_u)g). DLC=RMS(carga dinamica)/peso estatico. ' ...
 'Picos de aceleracao usam 5-30 s; curso maximo e N minimo consideram o ensaio completo, incluindo a partida.\n\n']);
fprintf(f,'## Semente de referencia: 1\n\n');
fprintf(f,'| Grandeza | Passiva | Semiativa |\n|---|---:|---:|\n');
fprintf(f,'| RMS a_s, 5-30 s [m/s^2] | %.6f | %.6f |\n',m.rms_as_passivo,m.rms_as_semi);
fprintf(f,'| Pico absoluto a_s, 5-30 s [m/s^2] | %.6f | %.6f |\n',m.pico_as_passivo,m.pico_as_semi);
fprintf(f,'| RMS carga dinamica, 5-30 s [N] | %.3f | %.3f |\n',m.rms_carga_pneu_passivo_N,m.rms_carga_pneu_semi_N);
fprintf(f,'| DLC, 5-30 s | %.5f | %.5f |\n',m.DLC_passivo,m.DLC_semi);
fprintf(f,'| Curso maximo, 0-30 s [cm] | %.4f | %.4f |\n',m.curso_max_passivo_cm,m.curso_max_semi_cm);
fprintf(f,'| N minimo, 0-30 s [N] | %.3f | %.3f |\n\n',m.N_min_passivo_N,m.N_min_semi_N);
fprintf(f,'Reducao de RMS da aceleracao: **%.3f%%**. Reducao da carga dinamica RMS: %.3f%%.\n\n', ...
 m.melhora_rms_pct,100*(1-m.rms_carga_pneu_semi_N/m.rms_carga_pneu_passivo_N));
fprintf(f,['Na semente 1, o RMS da carga dinamica aumentou %.2f%% e o curso maximo aumentou %.2f%%. ' ...
 'Portanto, a reducao de vibracao veio acompanhada de piora nesses dois indicadores.\n\n'], ...
 100*(m.rms_carga_pneu_semi_N/m.rms_carga_pneu_passivo_N-1), ...
 100*(m.curso_max_semi_cm/m.curso_max_passivo_cm-1));
fprintf(f,'Sensibilidade a janela: melhora 0-30 s = %.3f%%; 5-30 s = %.3f%%; 10-30 s = %.3f%%.\n\n', ...
 m.melhora_0_30_pct,m.melhora_rms_pct,m.melhora_10_30_pct);
fprintf(f,'## Cinco sementes pareadas\n\n');
fprintf(f,'| Semente | RMS passiva | RMS semiativa | Reducao [%%] | Nmin passiva [N] | Nmin semi [N] |\n|---:|---:|---:|---:|---:|---:|\n');
for j=1:height(T)
 fprintf(f,'| %d | %.6f | %.6f | %.3f | %.2f | %.2f |\n',T.semente(j),T.rms_as_passivo(j), ...
 T.rms_as_semi(j),T.melhora_rms_pct(j),T.N_min_passivo_N(j),T.N_min_semi_N(j));
end
fprintf(f,['\nMedia das reducoes pareadas: **%.3f%%**, desvio entre sementes %.3f pontos percentuais. ' ...
 'Razao das medias dos RMS: reducao %.3f%%. Sao estatisticas diferentes; nenhuma e intervalo de confianca.\n\n'], ...
 mean(T.melhora_rms_pct),std(T.melhora_rms_pct),100*(1-mean(T.rms_as_semi)/mean(T.rms_as_passivo)));
fprintf(f,'## Conferencia da pista\n\n');
fprintf(f,'Sigma teorico de conjunto = %.3f mm. Desvios medidos nos cinco trechos = ',1000*m.sigma_teorico_m);
fprintf(f,'%.3f ',1000*T.sigma_pista_m); fprintf(f,'mm.\n\n');
fprintf(f,['Um trecho finito pode diferir do sigma de conjunto por conter poucos ciclos longos. ' ...
 'A classe alvo e definida pelos coeficientes espectrais, nao por forcar sigma=15.2 mm. ' ...
 'PSD_pista.csv e pista_e_PSD_v2.png apresentam o periodograma unilateral espacial, ' ...
 'com detrend linear, janela Hann, agrupamento em 24 bandas log e media das cinco sementes. ' ...
 'A faixa 0.03-1.5 ciclos/m e usada para estimar Gd0 e inclinacao; conferencia_classe_C.csv ' ...
 'contem os valores. ' ...
 'Estimativa finita nao e certificacao normativa de pista medida.\n\n']);
fprintf(f,'## Interpretacao e limites\n\n');
fprintf(f,['A corrente da bobina atingiu %.4f A na semente 1, excedendo a referencia maxima de %.2f A em %.4f A. ' ...
 'O modelo limita a referencia de corrente, a tensao do driver e o amortecimento, mas nao impoe um limitador ideal ' ...
 'na corrente real da bobina. Trata-se de sobre-elevacao dinamica da malha original, que merece verificacao do atuador. ' ...
 'O parametro e a estrutura da v1 foram preservados, sem adicionar um limitador artificial.\n\n'], ...
 m.i_max_A,p.i_max,m.excesso_corrente_A);
if all(T.contato_valido_passivo & T.contato_valido_semi)
 fprintf(f,'N permaneceu positivo nas duas suspensoes em todos os cinco ensaios. Nao ocorreu violacao da hipotese de contato.\n\n');
else
 fprintf(f,['**Houve N <= 0 em pelo menos um ensaio.** O pneu linear bilateral nao modela voo e recontato. ' ...
 'As metricas desses ensaios sao resultados do modelo linear, com limitacao fisica apos a primeira perda de contato. ' ...
 'Nao se deve ocultar o fato nem afirmar aderencia validada. metricas_sementes.csv informa duracoes e Nmin.\n\n']);
 C=readtable(fullfile(pasta,'diagnostico_contato.csv'));
 fprintf(f,'| Semente | Primeiro N<=0 passivo [s] | Primeiro N<=0 semi [s] | Tempo N<=0 passivo [s] | Tempo N<=0 semi [s] |\n|---:|---:|---:|---:|---:|\n');
 for j=1:height(C)
  fprintf(f,'| %d | %.4f | %.4f | %.4f | %.4f |\n',C.semente(j), ...
   C.primeiro_N_nao_positivo_passivo_s(j),C.primeiro_N_nao_positivo_semi_s(j), ...
   C.tempo_N_nao_positivo_passivo_s(j),C.tempo_N_nao_positivo_semi_s(j));
 end
 fprintf(f,'\nNaN significa que nao houve N<=0. Duracao obtida por trapz do indicador N<=0 na malha de 0.5 ms.\n\n');
end
fprintf(f,['A reducao de RMS representa menor vibracao media quadratica; as curvas podem se cruzar e os picos ' ...
 'nao precisam cair na mesma proporcao. Avaliar simultaneamente carga dinamica e curso evita escolher ' ...
 'um controle apenas pelo conforto. O ganho 3000 e o da v1, sem otimizacao nesta etapa. ' ...
 'A comparacao nao comprova desempenho em toda pista classe C, outras velocidades ou veiculo real.\n\n']);
fprintf(f,'## Verificacao\n\n');
if ~isempty(checagens)
 c=readtable(fullfile(pasta,'convergencia_numerica.csv'));
 fprintf(f,['Testes aprovados: parametros fisicos e de controle iguais aos da v1, fases reprodutiveis, ' ...
 'RNG global preservado, energia exata das bandas, uma unica fonte de pista, passividade, limites de c e tensao, ' ...
 'equacoes mecanicas e comparacao com integracao RK4 independente do ramo passivo.\n\n']);
 fprintf(f,'Erro maximo dos estados passivos contra RK4 = %.3g. Com dt/2, RMS mudou %.5f%% (passiva) e %.5f%% (semiativa).\n\n', ...
 c.erro_RK4,100*c.delta_rel_RMS_passivo,100*c.delta_rel_RMS_semi);
else
 fprintf(f,'Validacao independente omitida nesta execucao. Execute executar_v2(true).\n\n');
end
fprintf(f,'## Entregas e escopo\n\n');
fprintf(f,['Modelo executavel: ../suspensao_semiativa_v2.slx. ' ...
 'Fontes em modelo/, visualizacao/, testes/ e ../parametros.m. ' ...
 'Graficos PNG e FIG editaveis, CSV de metricas, perfil e PSD e MAT de sinais completos. ' ...
 'varrer_ganhos_v2.m esta preparado para a etapa seguinte, sem mudar os parametros da v2. ' ...
 'Os scripts executam localmente; publicacao e tags sao feitas separadamente pelo Git. ' ...
 'Sinais MAT e figuras FIG sao regeneraveis e nao sao versionados.\n\n']);
fprintf(f,'## Referencias e requisitos fornecidos\n\n');
fprintf(f,['- Cronograma_Projeto_Suspensao.pdf, secao 4.2, tarefas da semana 2.\n' ...
 '- Resumo_ISO8608_ClasseC_72kmh.pdf, equacoes 1 a 4 e Quadro 2, 28/10/2026.\n' ...
 '- ISO 8608:2016: https://www.iso.org/standard/71202.html\n' ...
 '- Diaz-Choque et al. (2021), secao 6.1: https://doi.org/10.1155/2021/8084343\n' ...
 '- Agostinacchio et al. (2014): https://doi.org/10.1007/s12544-013-0127-8\n\n']);
fprintf(f,'Resumo agregado adicional: %d indicadores em resumo_cinco_sementes.csv.\n',height(resumo));
end
